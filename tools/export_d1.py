"""Export the local SQLite catalogue as D1-compatible INSERT statements.

The runtime schema stores JSON as TEXT, while the original import database uses
SQLite JSONB BLOBs. This exporter performs that conversion through SQLite's
json() function and deliberately emits no BEGIN/COMMIT statements.
"""

from __future__ import annotations

import argparse
import math
import sqlite3
from pathlib import Path
from typing import Any

REPO_ROOT = Path(__file__).resolve().parent.parent
DEFAULT_INPUT = REPO_ROOT / "data" / "pricebook.db"
DEFAULT_OUTPUT = REPO_ROOT / "data" / "pricebook.d1.sql"
MAX_STATEMENT_BYTES = 90_000

TABLE_ORDER = (
    "price_books",
    "categories",
    "products",
    "product_scopes",
    "product_variants",
    "product_codes",
    "colors",
    "color_aliases",
    "pricing_rules",
    "prices",
    "product_relations",
    "documents",
    "images",
    "image_links",
)

JSON_COLUMNS = {
    ("products", "properties"),
    ("product_variants", "properties"),
    ("product_variants", "constraints"),
    ("product_codes", "conditions"),
    ("colors", "properties"),
    ("pricing_rules", "scope"),
    ("pricing_rules", "conditions"),
    ("pricing_rules", "data"),
    ("prices", "conditions"),
    ("product_relations", "quantity"),
    ("product_relations", "conditions"),
    ("documents", "data"),
    ("image_links", "crop"),
}


def sql_literal(value: Any) -> str:
    if value is None:
        return "NULL"
    if isinstance(value, bool):
        return str(int(value))
    if isinstance(value, int):
        return str(value)
    if isinstance(value, float):
        if not math.isfinite(value):
            raise ValueError("D1 export cannot encode a non-finite REAL value")
        return repr(value)
    if isinstance(value, bytes):
        return f"X'{value.hex()}'"
    if isinstance(value, str):
        if "\x00" in value:
            raise ValueError("D1 export cannot encode NUL in a TEXT value")
        return "'" + value.replace("'", "''") + "'"
    raise TypeError(f"unsupported SQLite value type: {type(value).__name__}")


def validate_category_seed(connection: sqlite3.Connection) -> None:
    """Ensure INSERT OR IGNORE cannot hide a source/seed category mismatch."""
    seed = sqlite3.connect(":memory:")
    try:
        seed.executescript(
            (REPO_ROOT / "migrations" / "0001_initial_schema.sql").read_text(
                encoding="utf-8"
            )
        )
        expected = seed.execute("SELECT * FROM categories ORDER BY id").fetchall()
        actual = connection.execute("SELECT * FROM categories ORDER BY id").fetchall()
        if actual != expected:
            raise ValueError(
                "source categories differ from the D1 migration seed; "
                "migrate category IDs explicitly instead of exporting"
            )
    finally:
        seed.close()


def export(input_path: Path, output_path: Path) -> None:
    connection = sqlite3.connect(input_path)
    connection.execute("PRAGMA query_only = ON")
    validate_category_seed(connection)
    output_path.parent.mkdir(parents=True, exist_ok=True)

    total = 0
    with connection, output_path.open("w", encoding="utf-8", newline="\n") as output:
        output.write("-- Generated by tools/export_d1.py; JSONB converted to JSON TEXT.\n")
        for table in TABLE_ORDER:
            columns = [
                row[1]
                for row in connection.execute(f'PRAGMA table_info("{table}")').fetchall()
            ]
            if not columns:
                raise ValueError(f"source table is missing: {table}")
            selected = ", ".join(
                f'json("{column}") AS "{column}"'
                if (table, column) in JSON_COLUMNS
                else f'"{column}"'
                for column in columns
            )
            names = ", ".join(f'"{column}"' for column in columns)
            insert = "INSERT OR IGNORE" if table == "categories" else "INSERT"
            prefix = f'{insert} INTO "{table}" ({names}) VALUES\n'
            batch: list[str] = []
            batch_bytes = len(prefix.encode("utf-8"))
            count = 0

            def flush() -> None:
                nonlocal batch, batch_bytes
                if batch:
                    output.write(prefix + ",\n".join(batch) + ";\n")
                    batch = []
                    batch_bytes = len(prefix.encode("utf-8"))

            for row in connection.execute(f"SELECT {selected} FROM \"{table}\""):
                values = "(" + ", ".join(sql_literal(value) for value in row) + ")"
                size = len(values.encode("utf-8")) + 2
                if batch and batch_bytes + size > MAX_STATEMENT_BYTES:
                    flush()
                if batch_bytes + size > MAX_STATEMENT_BYTES:
                    raise ValueError(
                        f"one {table} row exceeds the safe D1 statement size; "
                        "split large documents or images before exporting"
                    )
                batch.append(values)
                batch_bytes += size
                count += 1
            flush()
            total += count
            print(f"{table}: {count} rows")
    print(f"Wrote {total} rows to {output_path}")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--input", type=Path, default=DEFAULT_INPUT)
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args()
    export(args.input, args.output)


if __name__ == "__main__":
    main()
